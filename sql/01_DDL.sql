CREATE TABLE comunidad_autonoma (
    id_ccaa  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(60) NOT NULL UNIQUE
);



CREATE TABLE provincia (
    id_provincia  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(60) NOT NULL UNIQUE,
    id_ccaa       INTEGER NOT NULL REFERENCES comunidad_autonoma (id_ccaa)
);

-- Municipio: el nombre solo es único dentro de su provincia
CREATE TABLE municipio (
    id_municipio  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(120) NOT NULL,
    id_provincia  INTEGER NOT NULL REFERENCES provincia (id_provincia),
    CONSTRAINT uq_municipio UNIQUE (id_provincia, nombre)
);

-- Localidad: el nombre solo es único dentro de su municipio
CREATE TABLE localidad (
    id_localidad  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(120) NOT NULL,
    id_municipio  INTEGER NOT NULL REFERENCES municipio (id_municipio),
    CONSTRAINT uq_localidad UNIQUE (id_municipio, nombre)
);

-- Empresa que opera la estación (columna "Rótulo" del Excel)
CREATE TABLE empresa (
    id_empresa  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(150) NOT NULL UNIQUE
);

-- Catálogo de carburantes (Gasolina 95 E5, Gasóleo A...)
CREATE TABLE carburante (
    id_carburante  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(60) NOT NULL UNIQUE
);

-- Estación: terrestre o marítima
CREATE TABLE estacion (
    id_estacion          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_estacion        VARCHAR(10) NOT NULL CHECK (tipo_estacion IN ('TERRESTRE', 'MARITIMA')),
    id_empresa           INTEGER NOT NULL REFERENCES empresa (id_empresa),
    id_localidad         INTEGER NOT NULL REFERENCES localidad (id_localidad),
    codigo_postal        CHAR(5),
    direccion            VARCHAR(255) NOT NULL,
    margen               CHAR(1) CHECK (margen IN ('D', 'I', 'N')),
    latitud              NUMERIC(9,6) CHECK (latitud BETWEEN -90 AND 90),
    longitud             NUMERIC(9,6) CHECK (longitud BETWEEN -180 AND 180),
    fecha_actualizacion  TIMESTAMP NOT NULL,
    horario              TEXT,
    tipo_venta           CHAR(1),
    remision             VARCHAR(2) CHECK (remision IN ('OM', 'dm')),
    tipo_servicio        TEXT,
    -- Terrestres: P = público, R = restringida a socios
    -- Marítimas:  P = pesqueros, R = recreo, M = mixto
    CONSTRAINT ck_tipo_venta CHECK (
        tipo_venta IS NULL
        OR (tipo_estacion = 'TERRESTRE' AND tipo_venta IN ('P', 'R'))
        OR (tipo_estacion = 'MARITIMA'  AND tipo_venta IN ('P', 'R', 'M'))
    )
);


-- Precio: relación N:M entre estación y carburante
CREATE TABLE precio (
    id_estacion     INTEGER NOT NULL REFERENCES estacion (id_estacion) ON DELETE CASCADE,
    id_carburante   INTEGER NOT NULL REFERENCES carburante (id_carburante),
    precio          NUMERIC(6,3) NOT NULL CHECK (precio > 0),
    porcentaje_bio  NUMERIC(5,2) CHECK (porcentaje_bio BETWEEN 0 AND 100),
    PRIMARY KEY (id_estacion, id_carburante)
);

-- Índices para acelerar las consultas
CREATE INDEX ix_provincia_ccaa       ON provincia (id_ccaa);
CREATE INDEX ix_municipio_provincia  ON municipio (id_provincia);
CREATE INDEX ix_localidad_municipio  ON localidad (id_municipio);
CREATE INDEX ix_estacion_empresa     ON estacion  (id_empresa);
CREATE INDEX ix_estacion_localidad   ON estacion  (id_localidad);
CREATE INDEX ix_estacion_tipo        ON estacion  (tipo_estacion);
CREATE INDEX ix_precio_carburante    ON precio    (id_carburante, precio);
